/**
 ******************************************************************************
 * @file    main.c
 * @brief   四灯流水灯实验（程序二：含核心板板载 PC13 灯）
 *
 *  实验要求：
 *    STM32F103C8T6 最小系统核心板 + 面包板 + 3只(或更多)红绿蓝LED，
 *    使用 GPIOA、GPIOB、GPIOC 三个端口的引脚控制LED轮流闪烁，间隔1秒；
 *    并将核心板板载的 PC13 灯也加入流水灯。
 *
 *  引脚分配（与 led.c 中的 LED_TABLE 一致）：
 *    PA0  → 红色LED（面包板，高电平点亮）
 *    PB0  → 绿色LED（面包板，高电平点亮）
 *    PC0  → 蓝色LED（面包板，高电平点亮）
 *    PC13 → 核心板板载LED（低电平点亮）
 *
 *  时钟：保持复位后的默认配置——HSI 8MHz，AHB/APB 不分频。
 *        整个程序不依赖任何库函数，纯寄存器操作。
 *
 *  实验现象：
 *    红 → 绿 → 蓝 → 板载灯 依次点亮，每只点亮1秒后熄灭，
 *    然后从红灯开始下一轮，周而复始形成流水灯效果。
 ******************************************************************************
 */
#include "led.h"
#include "delay.h"

/**
 * @brief  系统初始化（供启动文件调用）
 *
 *  Keil 的启动文件 startup_stm32f10x_md.s 在复位后、跳转到 main()
 *  之前会先调用 SystemInit()。本实验保持复位后的默认时钟
 *  （HSI 8MHz，AHB/APB 不分频），无需任何时钟配置，故为空实现。
 *
 *  ★ 注意：如果你的工程模板中带有标准库的 system_stm32f10x.c
 *    （它会把时钟倍频到 72MHz），请二选一：
 *     ① 把该文件移出工程，使用本工程的空 SystemInit（时钟保持8MHz）；
 *     ② 保留它，并把 delay.c 中的 SYSCLK_HZ 改为 72000000UL。
 */
void SystemInit(void)
{
}

/**
 * @brief  主函数
 *        初始化LED → 无限循环轮流点亮每一只LED，每次保持1秒
 */
int main(void)
{
    uint8_t i;

    LED_Init();                        /* 使能端口时钟，配置4个引脚为推挽输出 */

    while (1)
    {
        /* 一轮流水：按 LED_TABLE 的顺序逐只点亮 */
        for (i = 0; i < LED_NUM; i++)
        {
            LED_On((LedId_t)i);        /* 点亮第 i 只 LED           */
            delay_ms(1000);            /* 保持 1 秒                 */
            LED_Off((LedId_t)i);       /* 熄灭第 i 只 LED           */
            /* 熄灭与下一只点亮之间只有几个微秒，
               人眼完全察觉不到这个间隔 */
        }
        /* 一轮结束，回到循环开头，从红灯开始下一轮 */
    }
}
